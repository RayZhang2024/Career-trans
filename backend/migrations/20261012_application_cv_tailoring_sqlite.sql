-- Additive V2B review records; final preparations remain immutable.
CREATE TABLE IF NOT EXISTS application_cv_tailoring_sessions (
 id VARCHAR(36) PRIMARY KEY,
 user_id VARCHAR(36) NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 discovered_job_id VARCHAR(36) NOT NULL,
 client_request_id VARCHAR(36) NOT NULL,
 request_fingerprint VARCHAR(64) NOT NULL,
 status VARCHAR(32) NOT NULL,
 strategy_status VARCHAR(32) NOT NULL,
 draft_status VARCHAR(32) NOT NULL DEFAULT 'not_started',
 target_snapshot_json TEXT NOT NULL,
 identity_snapshot_json TEXT NOT NULL,
 profile_outline_json TEXT NOT NULL DEFAULT '{}',
 candidate_fingerprint VARCHAR(64) NOT NULL,
 candidate_evaluation_fingerprint VARCHAR(64) NOT NULL,
 evaluation_contract_fingerprint VARCHAR(64) NOT NULL,
 evaluation_id VARCHAR(36) NOT NULL,
 runtime_fingerprint VARCHAR(64) NOT NULL,
 provider VARCHAR(32) NOT NULL,
 model VARCHAR(120) NOT NULL,
 target_pages INTEGER NOT NULL DEFAULT 2,
 strategy_json TEXT NULL,
 strategy_review_json TEXT NOT NULL DEFAULT '{}',
 strategy_history_json TEXT NOT NULL DEFAULT '[]',
 strategy_revision INTEGER NOT NULL DEFAULT 0,
 draft_client_request_id VARCHAR(36) NULL,
 draft_json TEXT NULL,
 draft_history_json TEXT NOT NULL DEFAULT '[]',
 draft_revision INTEGER NOT NULL DEFAULT 0,
 failure_code VARCHAR(64) NULL,
 approved_preparation_id VARCHAR(36) NULL REFERENCES application_preparations(id) ON DELETE SET NULL,
 runtime_attribution_json TEXT NULL,
 created_at DATETIME NOT NULL,
 updated_at DATETIME NOT NULL,
 CONSTRAINT uq_cv_tailoring_request_user UNIQUE (user_id, client_request_id),
 CONSTRAINT uq_cv_tailoring_draft_request_user UNIQUE (user_id, draft_client_request_id)
);
CREATE INDEX IF NOT EXISTS ix_application_cv_tailoring_sessions_user_id ON application_cv_tailoring_sessions(user_id);
CREATE INDEX IF NOT EXISTS ix_cv_tailoring_user_job_created ON application_cv_tailoring_sessions(user_id, discovered_job_id, created_at);
